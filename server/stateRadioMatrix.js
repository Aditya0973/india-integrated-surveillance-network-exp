export function resolveStateFromCoords(lat, lon) {
  if (lat >= 28.40 && lat <= 28.88 && lon >= 76.84 && lon <= 77.34) return "Delhi";
  if (lat >= 23.80 && lat <= 30.50 && lon >= 77.00 && lon <= 84.60) return "Uttar Pradesh";
  if (lat >= 15.50 && lat <= 22.00 && lon >= 72.50 && lon <= 80.50) return "Maharashtra";
  if (lat >= 11.50 && lat <= 18.50 && lon >= 74.00 && lon <= 78.50) return "Karnataka";
  if (lat >= 8.00 && lat <= 13.50 && lon >= 76.50 && lon <= 80.50) return "Tamil Nadu";
  if (lat >= 15.80 && lat <= 19.80 && lon >= 77.20 && lon <= 81.50) return "Telangana";
  if (lat >= 21.50 && lat <= 27.50 && lon >= 85.50 && lon <= 89.90) return "West Bengal";
  if (lat >= 23.00 && lat <= 30.20 && lon >= 69.50 && lon <= 78.30) return "Rajasthan";
  if (lat >= 29.50 && lat <= 32.50 && lon >= 73.80 && lon <= 77.00) return "Punjab";
  if (lat >= 20.00 && lat <= 24.50 && lon >= 68.20 && lon <= 74.50) return "Gujarat";
  if (lat >= 8.00 && lat <= 12.80 && lon >= 74.50 && lon <= 77.80) return "Kerala";
  if (lat >= 32.20 && lat <= 37.00 && lon >= 73.50 && lon <= 80.00) return "Jammu & Kashmir / Ladakh";

  // Centroid proximity fallback for edge cases within India
  let nearestState = "Delhi";
  let minDistanceSq = Number.MAX_VALUE;
  for (const item of STATE_CENTROIDS) {
    const dLat = lat - item.lat;
    const dLon = lon - item.lon;
    const distSq = dLat * dLat + dLon * dLon;
    if (distSq < minDistanceSq) {
      minDistanceSq = distSq;
      nearestState = item.state;
    }
  }
  return nearestState;
}

